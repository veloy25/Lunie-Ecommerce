from __future__ import annotations

from collections.abc import Sequence
from typing import Any, Protocol


class ProductRepository(Protocol):
    def get(self, product_id: str) -> Any | None: ...
    def list_active(self, category: str | None = None, search: str | None = None) -> Sequence[Any]: ...
    def save(self, product: Any) -> Any: ...


class UserRepository(Protocol):
    def find_by_google_sub(self, subject: str) -> Any | None: ...
    def find_by_email(self, email: str) -> Any | None: ...
    def save(self, user: Any) -> Any: ...


class AuthenticationProvider(Protocol):
    async def authorization_redirect(self, request: Any) -> Any: ...
    async def exchange_and_validate(self, request: Any, code_verifier: str) -> dict[str, Any]: ...


class PaymentProvider(Protocol):
    def is_configured(self) -> bool: ...
    async def create_checkout(self, order: Any, items: Sequence[Any]) -> dict[str, Any]: ...
    def verify_webhook(self, signature: str, request_id: str, data_id: str) -> bool: ...
    async def get_payment(self, payment_id: str) -> dict[str, Any]: ...


class ShippingProvider(Protocol):
    def is_configured(self) -> bool: ...
    async def quote(self, items: Sequence[tuple[Any, int]], destination_postal_code: str) -> list[dict[str, Any]]: ...
    async def create_label(self, order: Any, session: Any) -> dict[str, Any]: ...
    def verify_webhook(self, signature: str, raw_body: bytes) -> bool: ...
